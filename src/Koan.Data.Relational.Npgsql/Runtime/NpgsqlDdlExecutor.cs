using Koan.Data.Abstractions;
using Koan.Data.Relational.Orchestration;
using Npgsql;

namespace Koan.Data.Relational.Npgsql.Runtime;

/// <summary>
/// How a PostgreSQL-wire store spells a schema, a table and a column. Every decision behind these words belongs
/// to the schema orchestrator; this speaks over a connection the repository has already opened, for one schema
/// operation. Connecting here creates nothing, so the repository can open before consent is settled.
/// </summary>
/// <param name="connection">The connection the repository opened for this schema operation.</param>
/// <param name="dialect">The dialect whose read each index expression repeats.</param>
/// <param name="verifyIndexes">
/// PostgreSQL index names are schema-wide and truncated to 63 bytes, so each index is named to fit and each created
/// index is confirmed in the catalog (NK-056, DATA-0146). CockroachDB scopes index names to their table and does not
/// truncate, so it passes false and keeps the names as declared.
/// </param>
/// <param name="partitioned">
/// Whether the table is a partition of its entity, so that a declared index name, shared by every partition table, is
/// qualified to belong to this one.
/// </param>
internal sealed class NpgsqlDdlExecutor(
    NpgsqlConnection connection,
    NpgsqlDialect dialect,
    bool verifyIndexes = false,
    bool partitioned = false)
    : IRelationalDdlExecutor
{
    private readonly Dictionary<string, string> _claimed = new(StringComparer.Ordinal);

    public async Task<RelationalTableShape?> Describe(RelationalTableDefinition table, CancellationToken ct = default)
    {
        await using var command = connection.CreateCommand();
        command.CommandText = """
            SELECT c.column_name, k.ordinal_position
              FROM information_schema.columns AS c
              LEFT JOIN information_schema.table_constraints AS t
                ON t.table_schema = c.table_schema
               AND t.table_name = c.table_name
               AND t.constraint_type = 'PRIMARY KEY'
              LEFT JOIN information_schema.key_column_usage AS k
                ON k.constraint_name = t.constraint_name
               AND k.table_schema = c.table_schema
               AND k.table_name = c.table_name
               AND k.column_name = c.column_name
             WHERE c.table_schema = @schema AND c.table_name = @table
             ORDER BY c.ordinal_position
            """;
        command.Parameters.AddWithValue("schema", table.Schema);
        command.Parameters.AddWithValue("table", table.Name);

        var columns = new Dictionary<string, RelationalColumnState?>(StringComparer.OrdinalIgnoreCase);
        var key = new List<(int Ordinal, string Name)>();
        await using (var reader = await command.ExecuteReaderAsync(ct).ConfigureAwait(false))
        {
            while (await reader.ReadAsync(ct).ConfigureAwait(false))
            {
                var name = reader.GetString(0);
                // Presence only. This runtime has never compared column definitions, and starting to would judge
                // every existing database against expectations no release has ever held it to; that is a
                // capability of its own, with its own proof, not a side effect of moving the decision.
                columns[name] = null;
                if (!reader.IsDBNull(1)) key.Add((reader.GetInt32(1), name));
            }
        }

        return columns.Count == 0
            ? null
            : new RelationalTableShape(
                columns,
                key.OrderBy(static part => part.Ordinal).Select(static part => part.Name).ToArray());
    }

    public Task Create(RelationalTableDefinition table, CancellationToken ct = default)
    {
        var definitions = table.Columns
            .Select(column => $"{NpgsqlDialect.Quote(column.Name)} {StoreType(column)}" +
                              (column.IsIdentity && column.IsGenerated ? " GENERATED BY DEFAULT AS IDENTITY" : string.Empty) +
                              " NOT NULL")
            .ToList();
        definitions.Add($"PRIMARY KEY ({string.Join(", ", table.Identity.Select(NpgsqlDialect.Quote))})");
        return Execute(
            $"CREATE SCHEMA IF NOT EXISTS {NpgsqlDialect.Quote(table.Schema)}; " +
            $"CREATE TABLE IF NOT EXISTS {Qualify(table)} ({string.Join(", ", definitions)})",
            ct);
    }

    public Task AddColumn(RelationalTableDefinition table, RelationalColumnDefinition column, CancellationToken ct = default) =>
        // Never NOT NULL: a populated table rejects one without a default, and the only columns this store
        // declares NOT NULL arrive with the table itself.
        Execute(
            $"ALTER TABLE {Qualify(table)} " +
            $"ADD COLUMN IF NOT EXISTS {NpgsqlDialect.Quote(column.Name)} {StoreType(column)}",
            ct);

    public async Task CreateIndex(
        RelationalTableDefinition table,
        RelationalIndexDefinition index,
        CancellationToken ct = default)
    {
        var name = verifyIndexes ? NpgsqlIndexNames.Name(table, index, partitioned) : index.Name;
        var effective = verifyIndexes ? NpgsqlIndexNames.Claim(_claimed, table, name) : name;
        // The indexed term is the dialect's own read, so it is the expression queries emit. PostgreSQL uses an
        // expression index only on an exact match, so a spelling of its own here would build an index the
        // planner never chooses. Every cast this dialect produces - boolean, bigint, numeric - is immutable,
        // which is what makes the expression indexable at all.
        var terms = index.Parts.Select(part => part.Path.IsNested
            ? $"({dialect.Read(part.Path, MappingValueShape.Scalar, part.PhysicalType)})"
            : NpgsqlDialect.Quote(part.Path.Name));
        await Execute(
            $"CREATE {(index.Unique ? "UNIQUE " : string.Empty)}INDEX IF NOT EXISTS " +
            $"{NpgsqlDialect.Quote(effective)} ON {Qualify(table)} ({string.Join(", ", terms)})",
            ct).ConfigureAwait(false);
        // IF NOT EXISTS skips on any index of that name in the schema, whatever table or keys it has, so the catalog is
        // asked what the name now holds.
        if (verifyIndexes)
            NpgsqlIndexNames.Verify(table, index, effective, await Catalog(table.Schema, effective, ct).ConfigureAwait(false));
    }

    public async Task<RelationalIndexState?> FindIndex(
        RelationalTableDefinition table,
        RelationalIndexDefinition index,
        CancellationToken ct = default)
    {
        // The catalog lookup is the same one DATA-0142's verification uses, so it is only asked where that holds:
        // PostgreSQL, whose index names are schema-wide.
        if (!verifyIndexes) return null;
        var name = NpgsqlIndexNames.Effective(NpgsqlIndexNames.Name(table, index, partitioned));
        var found = await Catalog(table.Schema, name, ct).ConfigureAwait(false);
        return found.Any(entry => string.Equals(entry.Table, table.Name, StringComparison.Ordinal))
            ? new RelationalIndexState(name, $"DROP INDEX {NpgsqlDialect.Quote(table.Schema)}.{NpgsqlDialect.Quote(name)};")
            : null;
    }

    /// <summary>
    /// Adds the stored generated <c>tsvector</c> column and its GIN index (<see cref="NpgsqlLexical"/>), or replaces
    /// the column when its recorded recipe differs from the declaration. The server computes the column for every row
    /// the table already holds, so the index is current as soon as it exists.
    /// </summary>
    public async Task CreateLexicalIndex(
        RelationalTableDefinition table,
        RelationalLexicalDefinition lexical,
        CancellationToken ct = default)
    {
        var column = NpgsqlDialect.Quote(NpgsqlLexical.ColumnName);
        var stamp = NpgsqlLexical.Stamp(dialect, lexical);
        var held = await LexicalStamp(table, ct).ConfigureAwait(false);
        if (held is not null && !string.Equals(held, stamp, StringComparison.Ordinal))
        {
            // Dropping the column drops the index that depends on it; both are built again below.
            await Execute($"ALTER TABLE {Qualify(table)} DROP COLUMN {column}", ct).ConfigureAwait(false);
            held = null;
        }
        if (held is null)
            await Execute(
                $"ALTER TABLE {Qualify(table)} ADD COLUMN {column} tsvector " +
                $"GENERATED ALWAYS AS ({NpgsqlLexical.Vector(dialect, lexical)}) STORED; " +
                $"COMMENT ON COLUMN {Qualify(table)}.{column} IS '{stamp.Replace("'", "''", StringComparison.Ordinal)}'",
                ct).ConfigureAwait(false);
        await Execute(
            $"CREATE INDEX IF NOT EXISTS {NpgsqlDialect.Quote(NpgsqlLexical.IndexName(table))} " +
            $"ON {Qualify(table)} USING GIN ({column})",
            ct).ConfigureAwait(false);
    }

    public async Task<bool> HasLexicalIndex(
        RelationalTableDefinition table,
        RelationalLexicalDefinition lexical,
        CancellationToken ct = default)
    {
        var held = await LexicalStamp(table, ct).ConfigureAwait(false);
        if (!string.Equals(held, NpgsqlLexical.Stamp(dialect, lexical), StringComparison.Ordinal)) return false;
        await using var command = connection.CreateCommand();
        command.CommandText = "SELECT 1 FROM pg_indexes WHERE schemaname = @schema AND tablename = @table AND indexname = @name";
        command.Parameters.AddWithValue("schema", table.Schema);
        command.Parameters.AddWithValue("table", table.Name);
        command.Parameters.AddWithValue("name", NpgsqlLexical.IndexName(table));
        return await command.ExecuteScalarAsync(ct).ConfigureAwait(false) is not null;
    }

    /// <summary>The recipe recorded on the lexical column, or <see langword="null"/> when the table has no such column.</summary>
    private async Task<string?> LexicalStamp(RelationalTableDefinition table, CancellationToken ct)
    {
        await using var command = connection.CreateCommand();
        command.CommandText = """
            SELECT coalesce(col_description(c.oid, a.attnum), '')
              FROM pg_attribute AS a
              JOIN pg_class AS c ON c.oid = a.attrelid
              JOIN pg_namespace AS n ON n.oid = c.relnamespace
             WHERE n.nspname = @schema AND c.relname = @table AND a.attname = @column AND NOT a.attisdropped
            """;
        command.Parameters.AddWithValue("schema", table.Schema);
        command.Parameters.AddWithValue("table", table.Name);
        command.Parameters.AddWithValue("column", NpgsqlLexical.ColumnName);
        return await command.ExecuteScalarAsync(ct).ConfigureAwait(false) as string;
    }

    private async Task<IReadOnlyList<NpgsqlIndexNames.CatalogEntry>> Catalog(string schema, string name, CancellationToken ct)
    {
        await using var command = connection.CreateCommand();
        command.CommandText = """
            SELECT t.relname, i.indisunique, i.indnkeyatts
              FROM pg_class AS c
              JOIN pg_namespace AS n ON n.oid = c.relnamespace
              JOIN pg_index AS i ON i.indexrelid = c.oid
              JOIN pg_class AS t ON t.oid = i.indrelid
             WHERE n.nspname = @schema AND c.relname = @name
            """;
        command.Parameters.AddWithValue("schema", schema);
        command.Parameters.AddWithValue("name", name);
        var entries = new List<NpgsqlIndexNames.CatalogEntry>();
        await using var reader = await command.ExecuteReaderAsync(ct).ConfigureAwait(false);
        while (await reader.ReadAsync(ct).ConfigureAwait(false))
            entries.Add(new(reader.GetString(0), reader.GetBoolean(1), Convert.ToInt32(reader.GetValue(2))));
        return entries;
    }

    private async Task Execute(string sql, CancellationToken ct)
    {
        await using var command = connection.CreateCommand();
        command.CommandText = sql;
        await command.ExecuteNonQueryAsync(ct).ConfigureAwait(false);
    }

    private static string Qualify(RelationalTableDefinition table) =>
        $"{NpgsqlDialect.Quote(table.Schema)}.{NpgsqlDialect.Quote(table.Name)}";

    private static string StoreType(RelationalColumnDefinition column)
    {
        if (column.Shape == RelationalStorageShape.Structured) return "jsonb";
        var value = Nullable.GetUnderlyingType(column.ClrType) ?? column.ClrType;
        if (value.IsEnum) value = typeof(string);
        if (value == typeof(short) || value == typeof(byte) || value == typeof(sbyte)) return "smallint";
        if (value == typeof(int) || value == typeof(ushort)) return "integer";
        if (value == typeof(long) || value == typeof(uint)) return "bigint";
        if (value == typeof(bool)) return "boolean";
        if (value == typeof(decimal)) return "numeric";
        if (value == typeof(float)) return "real";
        if (value == typeof(double)) return "double precision";
        if (value == typeof(Guid)) return "uuid";
        if (value == typeof(DateTime)) return "timestamp";
        if (value == typeof(DateTimeOffset)) return "timestamptz";
        if (value == typeof(DateOnly)) return "date";
        if (value == typeof(TimeOnly)) return "time";
        if (value == typeof(TimeSpan)) return "interval";
        if (value == typeof(byte[])) return "bytea";
        return "text";
    }
}
